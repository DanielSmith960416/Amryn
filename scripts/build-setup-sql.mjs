/**
 * Builds supabase/setup.sql — every migration, in order, in one transaction.
 *
 * Applying eight files by hand has a failure mode that is hard to see: one of
 * them errors, the rest are pasted anyway, and the database is left half built
 * with no single moment where anything said so. The application then reports a
 * missing schema and the obvious response — run the migrations again — cannot
 * work, because `create table` on a table that already exists fails too.
 *
 * One file in one transaction removes that. It either applies completely or
 * changes nothing at all, and the error names the line it stopped on.
 *
 * Generated rather than kept by hand, so it cannot drift from the migrations
 * it is made of.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'supabase', 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();

/**
 * One object each migration introduces, used to work out what an existing
 * database has already had — see src/lib/db/ledger.ts.
 *
 * Enforced here rather than left to be noticed later: a migration with no
 * signature reads as never applied, so a database that already has it would be
 * told to run it again, and the run would fail on the first object that
 * already exists. Failing the build is the cheap moment to catch that.
 */
const signatures = JSON.parse(readFileSync(join(dir, 'signatures.json'), 'utf8'));
const unsigned = files.filter((file) => !signatures[file]);
if (unsigned.length > 0) {
  console.error(
    `No signature for ${unsigned.join(', ')}.\n` +
      'Add one to supabase/migrations/signatures.json: a SQL expression that is true only ' +
      'once that migration has been applied.',
  );
  process.exit(1);
}

const parts = [
  `-- Amryn™ AIGrowthIntelligence® — complete database setup`,
  `--`,
  `-- Generated by scripts/build-setup-sql.mjs from supabase/migrations.`,
  `-- Do not edit this file; edit the migrations and regenerate.`,
  `--`,
  `-- Paste the whole thing into the Supabase SQL editor and run it once.`,
  `-- It is wrapped in a single transaction: if any statement fails, nothing is`,
  `-- applied and the error names where it stopped. A half-applied schema is the`,
  `-- one outcome this exists to prevent.`,
  `--`,
  `-- Safe on an empty database. NOT safe to run twice — the second run fails on`,
  `-- the first \`create table\`, having changed nothing.`,
  ``,
  `begin;`,
  ``,
];

for (const file of files) {
  parts.push(
    `-- ══════════════════════════════════════════════════════════════════════`,
    `-- ${file}`,
    `-- ══════════════════════════════════════════════════════════════════════`,
    `do $setup$ begin raise notice 'applying ${file}'; end $setup$;`,
    ``,
    readFileSync(join(dir, file), 'utf8').trimEnd(),
    ``,
  );
}

parts.push(
  `-- ══════════════════════════════════════════════════════════════════════`,
  `-- Did it work?`,
  `-- ══════════════════════════════════════════════════════════════════════`,
  `do $setup$`,
  `declare`,
  `  tables_found bigint;`,
  `  perms_found  bigint;`,
  `  grants_found bigint;`,
  `begin`,
  `  select count(*) into tables_found from pg_tables where schemaname = 'public';`,
  `  select count(*) into perms_found  from public.permissions;`,
  `  select count(*) into grants_found from public.role_permissions;`,
  ``,
  `  if tables_found <> 49 then`,
  `    raise exception 'expected 49 tables, found %', tables_found;`,
  `  end if;`,
  `  if perms_found <> 30 then`,
  `    raise exception 'expected 30 permissions, found %', perms_found;`,
  `  end if;`,
  `  if grants_found < 100 then`,
  `    raise exception 'expected the role matrix to be seeded, found % grants', grants_found;`,
  `  end if;`,
  ``,
  `  raise notice 'setup complete: % tables, % permissions, % role grants',`,
  `    tables_found, perms_found, grants_found;`,
  `end $setup$;`,
  ``,
  `commit;`,
  ``,
  `-- Outside the transaction: PostgREST answers from a cached copy of the`,
  `-- schema, and nothing above is visible to the application until it is told.`,
  `notify pgrst, 'reload schema';`,
  ``,
);

const sql = parts.join('\n');
writeFileSync(join(root, 'supabase', 'setup.sql'), sql);

/**
 * The same SQL as a TypeScript module.
 *
 * The application applies its own schema, and it has to carry the statements
 * with it: a serverless bundle contains only what was imported at build time,
 * so reading supabase/setup.sql from disk at runtime finds nothing. JSON string
 * literal rather than a template literal, because the SQL is full of dollar
 * quoting and backslashes and a template literal would have to escape them.
 */
writeFileSync(
  join(root, 'src', 'lib', 'db', 'setup-sql.ts'),
  [
    '// Generated by scripts/build-setup-sql.mjs. Do not edit.',
    '// Edit the files in supabase/migrations and regenerate.',
    '',
    '/** Every migration, in order, in one transaction. */',
    `export const SETUP_SQL = ${JSON.stringify(sql)};`,
    '',
    '/** The migrations it was built from, for reporting what was applied. */',
    `export const MIGRATION_FILES = ${JSON.stringify(files, null, 2)};`,
    '',
    '/**',
    ' * The same migrations, individually.',
    ' *',
    ' * SETUP_SQL builds a database from nothing, which is the easy half. A',
    ' * database that already exists needs the files it has not seen and only',
    ' * those, each in its own transaction, so applying two changes to a live',
    ' * schema cannot leave it between them.',
    ' */',
    '/** One object each migration creates, for deciding whether it already has. */',
    `export const SIGNATURES: Record<string, string> = ${JSON.stringify(signatures, null, 2)};`,
    '',
    `export const MIGRATIONS: { file: string; sql: string }[] = ${JSON.stringify(
      files.map((file) => ({
        file,
        sql: readFileSync(join(dir, file), 'utf8').trimEnd(),
      })),
      null,
      2,
    )};`,
    '',
  ].join('\n'),
);

console.log(`supabase/setup.sql and src/lib/db/setup-sql.ts written from ${files.length} migrations`);
